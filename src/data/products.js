export function getProductById(id) {
  return PRODUCTS.find(p => p.id === id || p.slug === id);
}

export function getProductsByCategory(category) {
  if (!category || category === 'Todos') return PRODUCTS;
  if (category === 'Promoção') {
    return PRODUCTS.filter(p => p.compare_price || (p.badges && p.badges.includes('Promoção')));
  }
  return PRODUCTS.filter(p => p.category.toLowerCase().includes(category.toLowerCase()) || category.toLowerCase().includes(p.category.toLowerCase()));
}
