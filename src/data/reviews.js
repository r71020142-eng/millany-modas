// Calculate summary stats for a product
export function getProductRatingStats(productId) {
  const reviews = getProductReviews(productId);
  const count = reviews.length;
  if (count === 0) {
    return {
      average: 5.0,
      count: 0,
      distribution: { 5: 0, 4: 0, 3: 0, 2: 0, 1: 0 },
      withPhotosCount: 0,
      withCommentsCount: 0
    };
  }

  const distribution = { 5: 0, 4: 0, 3: 0, 2: 0, 1: 0 };
  let sum = 0;
  let withPhotosCount = 0;
  let withCommentsCount = 0;

  reviews.forEach((r) => {
    const star = Math.min(5, Math.max(1, Math.round(r.rating || 5)));
    distribution[star] = (distribution[star] || 0) + 1;
    sum += (r.rating || 5);
    if (r.images && r.images.length > 0) withPhotosCount++;
    if (r.comment && r.comment.trim()) withCommentsCount++;
  });

  const average = Number((sum / count).toFixed(1));

  return {
    average,
    count,
    distribution,
    withPhotosCount,
    withCommentsCount
  };
}

// Add a new review
export function addProductReview(newReview) {
  const all = getAllReviews();
  const created = {
    ...newReview,
    id: `rev_${Date.now()}_${Math.random().toString(36).substr(2, 5)}`,
    date: new Date().toISOString().replace('T', ' ').substring(0, 16),
    likes: 0,
    verifiedPurchase: true,
    sellerReply: null
  };
  const updated = [created, ...all];
  saveAllReviews(updated);
  return created;
}

// Toggle like
export function toggleReviewHelpful(reviewId) {
  const all = getAllReviews();
  const updated = all.map((r) => {
    if (r.id === reviewId) {
      const isLiked = r.userLiked;
      return {
        ...r,
        likes: isLiked ? Math.max(0, r.likes - 1) : r.likes + 1,
        userLiked: !isLiked
      };
    }
    return r;
  });
  saveAllReviews(updated);
  return updated;
}

// Add/Update seller reply
export function setSellerReply(reviewId, replyText) {
  const all = getAllReviews();
  const updated = all.map((r) => {
    if (r.id === reviewId) {
      return {
        ...r,
        sellerReply: replyText ? {
          text: replyText,
          date: new Date().toISOString().replace('T', ' ').substring(0, 16)
        } : null
      };
    }
    return r;
  });
  saveAllReviews(updated);
  return updated;
}

// Delete review
export function deleteReviewById(reviewId) {
  const all = getAllReviews();
  const updated = all.filter((r) => r.id !== reviewId);
  saveAllReviews(updated);
  return updated;
}
